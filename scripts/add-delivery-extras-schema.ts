import { config } from "dotenv";
import postgres from "postgres";

config();

async function main() {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");

  const sql = postgres(url, { max: 1 });

  await sql`
    CREATE TABLE IF NOT EXISTS not_posted_deliveries (
      id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      store_product_id integer NOT NULL REFERENCES store_products(id),
      quantity numeric(18, 4) NOT NULL,
      file_name varchar(500) NOT NULL,
      imported_at timestamptz NOT NULL DEFAULT now(),
      book_stock_imported_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `;

  await sql`
    ALTER TABLE not_posted_deliveries
    ADD COLUMN IF NOT EXISTS book_stock_imported_at timestamptz
  `;

  await sql`
    CREATE INDEX IF NOT EXISTS not_posted_deliveries_store_product_idx
    ON not_posted_deliveries (store_product_id)
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS not_posted_deliveries_imported_at_idx
    ON not_posted_deliveries (imported_at)
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS not_posted_deliveries_book_stock_imported_at_idx
    ON not_posted_deliveries (book_stock_imported_at)
  `;

  await sql`
    UPDATE not_posted_deliveries np
    SET book_stock_imported_at = latest.imported_at
    FROM (
      SELECT store_product_id, max(imported_at) AS imported_at
      FROM book_stock
      GROUP BY store_product_id
    ) latest
    WHERE np.store_product_id = latest.store_product_id
      AND np.book_stock_imported_at IS NULL
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS future_deliveries (
      id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      store_product_id integer NOT NULL REFERENCES store_products(id),
      quantity numeric(18, 4) NOT NULL,
      source varchar(20) NOT NULL DEFAULT 'ocs',
      supplier_id integer REFERENCES suppliers(id),
      file_name varchar(500) NOT NULL,
      imported_at timestamptz NOT NULL DEFAULT now(),
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE INDEX IF NOT EXISTS future_deliveries_store_product_idx
    ON future_deliveries (store_product_id)
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS future_deliveries_imported_at_idx
    ON future_deliveries (imported_at)
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS future_deliveries_source_idx
    ON future_deliveries (source)
  `;
  await sql`
    CREATE INDEX IF NOT EXISTS future_deliveries_supplier_idx
    ON future_deliveries (supplier_id)
  `;

  await sql.end();
  console.log("Delivery extras schema is ready.");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
