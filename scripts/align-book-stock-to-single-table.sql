-- Align book stock to a single qty table (like wastage / rtc_sales / promo_sales).
-- Run against the app database when ready.

CREATE TABLE IF NOT EXISTS book_stock (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_product_id integer NOT NULL REFERENCES store_products (id),
  book_stock_date date NOT NULL,
  book_stock_qty numeric(18, 4) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT book_stock_store_product_date_unique UNIQUE (store_product_id, book_stock_date)
);

-- Keep the newest qty when the same product appears on the same date across imports.
INSERT INTO book_stock (
  store_product_id,
  book_stock_date,
  book_stock_qty,
  created_at,
  updated_at
)
SELECT DISTINCT ON (i.store_product_id, bi.book_stock_date)
  i.store_product_id,
  bi.book_stock_date,
  i.quantity,
  bi.imported_at,
  bi.imported_at
FROM book_stock_items i
JOIN book_stock_imports bi ON bi.id = i.import_id
ORDER BY i.store_product_id, bi.book_stock_date, bi.imported_at DESC
ON CONFLICT (store_product_id, book_stock_date) DO UPDATE
SET
  book_stock_qty = EXCLUDED.book_stock_qty,
  updated_at = EXCLUDED.updated_at;

