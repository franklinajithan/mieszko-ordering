BEGIN;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS calculated_at timestamptz;
ALTER TABLE supplier_orders ADD COLUMN IF NOT EXISTS exported_at timestamptz;
CREATE INDEX IF NOT EXISTS supplier_orders_pending_idx ON supplier_orders(store_id) WHERE exported_at IS NULL;

CREATE TABLE IF NOT EXISTS import_quality_observations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id integer NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
 source_type text NOT NULL,
 problem_type text NOT NULL CHECK(problem_type IN ('unknown_product_code','unmatched_barcode')),
 reference text NOT NULL,
 first_seen_at timestamptz NOT NULL DEFAULT now(),
 last_seen_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT import_quality_observations_identity_unique UNIQUE(store_id,source_type,problem_type,reference)
);
COMMIT;
