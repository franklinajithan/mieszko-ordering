-- Mieszko Ordering: nightly import job audit log
-- Staged migration only. Apply on the OFFICE PostgreSQL database after review.
-- Non-destructive: does not alter existing sales, RTC, wastage or book-stock data.
BEGIN;
CREATE TABLE IF NOT EXISTS data_import_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id integer REFERENCES stores(id) ON DELETE SET NULL,
  source_type varchar(32) NOT NULL CHECK (source_type IN ('normal_sales','rtc','wastage','book_stock')),
  trigger_type varchar(16) NOT NULL CHECK (trigger_type IN ('nightly','manual','retry')),
  status varchar(16) NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','downloading','downloaded','importing','success','failed')),
  source_file_name text,
  source_file_path text,
  source_start_date date,
  source_end_date date,
  downloaded_at timestamptz,
  imported_at timestamptz,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  downloaded_row_count integer,
  imported_row_count integer,
  rejected_row_count integer,
  error_message text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT data_import_runs_counts_nonnegative CHECK (
    (downloaded_row_count IS NULL OR downloaded_row_count >= 0)
    AND (imported_row_count IS NULL OR imported_row_count >= 0)
    AND (rejected_row_count IS NULL OR rejected_row_count >= 0)
  )
);
CREATE INDEX IF NOT EXISTS data_import_runs_store_source_started_idx
  ON data_import_runs (store_id, source_type, started_at DESC);
CREATE INDEX IF NOT EXISTS data_import_runs_status_started_idx
  ON data_import_runs (status, started_at DESC);
COMMIT;
