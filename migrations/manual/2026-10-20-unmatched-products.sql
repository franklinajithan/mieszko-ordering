BEGIN;
CREATE TABLE IF NOT EXISTS crm_product_identifiers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id integer NOT NULL REFERENCES stores(id),
 kind text NOT NULL CHECK(kind IN ('Barcode','Product code')),
 identifier text NOT NULL,
 product_name text,
 store_product_id integer REFERENCES store_products(id),
 first_seen_at timestamptz NOT NULL DEFAULT now(),
 last_checked_at timestamptz NOT NULL DEFAULT now(),
 resolved_at timestamptz,
 UNIQUE(store_id,kind,identifier),
 CHECK((store_product_id IS NULL) = (resolved_at IS NULL))
);
CREATE INDEX IF NOT EXISTS crm_product_identifiers_pending_idx ON crm_product_identifiers(store_id,store_product_id,id);
CREATE TABLE IF NOT EXISTS crm_identifier_occurrences (
 identifier_id bigint NOT NULL REFERENCES crm_product_identifiers(id),
 run_id bigint NOT NULL REFERENCES data_import_runs(id),
 transaction_count integer,
 PRIMARY KEY(identifier_id,run_id)
);
CREATE TABLE IF NOT EXISTS crm_product_code_aliases (
 store_id integer NOT NULL REFERENCES stores(id),
 identifier varchar(100) NOT NULL,
 store_product_id integer NOT NULL REFERENCES store_products(id),
 PRIMARY KEY(store_id,identifier)
);
-- Worker uses the same alias relation. Trigger also protects non-application writers.
CREATE OR REPLACE FUNCTION check_crm_mapping_store() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(73501,NEW.store_id);
 IF NOT EXISTS(SELECT 1 FROM store_products WHERE id=NEW.store_product_id AND store_id=NEW.store_id) THEN
  RAISE EXCEPTION 'CRM mapping belongs to another store';
 END IF;
 IF TG_TABLE_NAME='crm_product_code_aliases' AND EXISTS(
  SELECT 1 FROM store_products WHERE store_id=NEW.store_id AND store_product_code=NEW.identifier AND id<>NEW.store_product_id
 ) THEN RAISE EXCEPTION 'CRM alias conflicts with existing product code'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS crm_alias_store_check ON crm_product_code_aliases;
CREATE TRIGGER crm_alias_store_check BEFORE INSERT OR UPDATE ON crm_product_code_aliases FOR EACH ROW EXECUTE FUNCTION check_crm_mapping_store();
DROP TRIGGER IF EXISTS crm_identifier_store_check ON crm_product_identifiers;
CREATE TRIGGER crm_identifier_store_check BEFORE INSERT OR UPDATE ON crm_product_identifiers FOR EACH ROW WHEN (NEW.store_product_id IS NOT NULL) EXECUTE FUNCTION check_crm_mapping_store();
CREATE TABLE IF NOT EXISTS crm_reconciliation_batches (
 id uuid PRIMARY KEY,
 rows jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 approved_at timestamptz,
 approved_by text,
 result jsonb
);
CREATE TABLE IF NOT EXISTS crm_reconciliation_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identifier_id bigint NOT NULL REFERENCES crm_product_identifiers(id),
 batch_id uuid REFERENCES crm_reconciliation_batches(id),
 store_product_id integer REFERENCES store_products(id),
 action text NOT NULL,
 operator_name text NOT NULL,
 notes text,
 supplier_code text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS crm_audit_identifier_idx ON crm_reconciliation_audit(identifier_id,id DESC);
-- Validated normalized report data, isolated from published totals until complete.
CREATE TABLE IF NOT EXISTS crm_report_stage (
 run_id bigint NOT NULL REFERENCES data_import_runs(id),
 identifier varchar(100) NOT NULL,
 report_date date NOT NULL,
 quantity numeric(18,4) NOT NULL,
 mapping_type text NOT NULL CHECK(mapping_type IN ('barcode','store_product_code')),
 PRIMARY KEY(run_id,identifier,report_date)
);
-- Coordinate legacy Product Upload and barcode editing with approval transactions.
CREATE OR REPLACE FUNCTION lock_crm_product_store() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(73501,NEW.store_id);
 IF TG_TABLE_NAME='store_products' THEN
  IF EXISTS(SELECT 1 FROM crm_product_code_aliases WHERE store_id=NEW.store_id AND identifier=NEW.store_product_code AND store_product_id<>NEW.id)
   THEN RAISE EXCEPTION 'Product code conflicts with approved CRM alias'; END IF;
 ELSE
  IF NOT EXISTS(SELECT 1 FROM store_products WHERE id=NEW.store_product_id AND store_id=NEW.store_id)
   THEN RAISE EXCEPTION 'Barcode belongs to another store'; END IF;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS crm_product_store_lock ON store_products;
CREATE TRIGGER crm_product_store_lock BEFORE INSERT OR UPDATE ON store_products FOR EACH ROW EXECUTE FUNCTION lock_crm_product_store();
DROP TRIGGER IF EXISTS crm_barcode_store_lock ON product_barcodes;
CREATE TRIGGER crm_barcode_store_lock BEFORE INSERT OR UPDATE ON product_barcodes FOR EACH ROW EXECUTE FUNCTION lock_crm_product_store();
COMMIT;
